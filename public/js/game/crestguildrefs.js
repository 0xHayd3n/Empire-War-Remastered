// Standalone SVG string, 1024 x 1024, for the named guild crest. `mask`
// returns projector coverage and relief, without the colored carrier.
export function guildSvg(key, mask = false, ink = null) {
  const stencil = mask || ink;
  let body =
    key === 'banking'
      ? stencil ? bankingMask : bankingFace
      : key === 'techno'
        ? stencil ? technoMask : technoFace
        : '';
  if (!mask && /^#[0-9a-f]{6}$/i.test(ink)) body = body.replace(/fill="#(?:fff|888)"/g, `fill="${ink}"`);
  return body ? `<svg ${frame}>${body}</svg>` : '';
}
