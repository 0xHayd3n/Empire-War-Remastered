// Emit public metadata only, never mounted bytes. Intentional review list: not a name classifier.
import { readFileSync as read, writeFileSync as write } from 'node:fs';
import { createHash } from 'node:crypto';
import { requireDirection } from './direction.mjs';
import { completeTerrain } from './terrain-policy.mjs';
import os from 'node:os';
import { openScope, scope } from './survey.mjs';
import { readLibrary } from '../workshop-library.mjs';
import { parseALO } from '../../public/js/alo.js';
import path from 'node:path';
const id = 'd96aa07683839825c24b8653663e554a88948f6d4e2ff1a198d77b426f1bb03e',
  job = JSON.parse(read(path.join(os.tmpdir(), 'universal-map-remaster-v1/jobs', id + '.json')));
const hash = b => createHash('sha256').update(b).digest('hex');
if (hash(JSON.stringify(job.identity)) !== id) throw Error('Not the reviewed job');
const direction = requireDirection(job);
const { policy, stamp, slots, donors, zones, composition } = completeTerrain(job, direction);
const art = new URL('../../public/art/', import.meta.url),
  grove = new URL('endor-grove/', art),
  names = ['models.json', 'fern2-fern.bin', 'fern.png', 'fern-normal.png'];
const jungle = new URL('yavin-jungle/', art),
  files = [
    'models.json',
    'jacaranda.png',
    'jacaranda.bin',
    'jacaranda-far.bin',
    'anthurium.png',
    'anthurium-normal.png',
    'anthurium.bin',
    'anthurium-wide.bin',
    'anthurium-young.bin'
  ];
const canopy = { files: Object.fromEntries(files.map(n => [n, hash(read(new URL(n, jungle)))])), targets: {}, sources: {} };
const lib = readLibrary(),
  vfs = openScope(lib, scope(lib, 'foc'));
try {
  for (const [base, count, stems, radius, herb] of [
    ['W_TREE_EVER_00_HI', 196, 1, 0],
    ['W_TREE_EVER_01_HI', 199, 1, 0],
    ['W_TREE_EVER_00_CLUSTER', 2, 4, 66],
    ['W_TREE_EVER_01_CLUSTER', 4, 4, 62],
    ['W_TREE_EVER_CANOPY_A', 19, 7, 125],
    ['W_TREE_EVER_CANOPY_B', 148, 7, 130],
    ['W_GRNDCVR_A', 399, 4, 26, true],
    ['W_GRNDCVR_B', 359, 3, 25, true],
    ['W_GRNDCVR_D', 354, 5, 29, true]
  ]) {
    const name = base + '.ALO',
      key = 'Data/Art/Models/' + name,
      b = vfs.read(vfs.resolve(key));
    canopy.sources[key] = hash(b);
    canopy.targets[name] = { count, stems, radius, herb: !!herb };
    const m = parseALO(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
    for (const mesh of m.meshes)
      for (const sub of mesh.subs)
        for (const [k, n] of Object.entries(sub.material?.params || {}))
          if (typeof n === 'string' && /Texture$/i.test(k) && n && !/^none$/i.test(n)) {
            const key = 'Data/Art/Textures/' + (/\.[a-z0-9]{2,4}$/i.test(n) ? n : n + '.dds');
            const b = vfs.read(vfs.resolve(key));
            if (!b) throw Error('Missing model dependency ' + key);
            canopy.sources[key] = hash(b);
          }
  }
} finally {
  vfs.close();
}
const distal=new URL('yavin-groundcover/',art), catalog=JSON.parse(read(new URL('models.json',distal)));
const farCover={atlas:catalog.atlas.file,files:Object.fromEntries(['models.json',catalog.atlas.file,...catalog.models.map(m=>m.file)].map(f=>[f,hash(read(new URL(f,distal)))]))};
for(const m of catalog.models)if(farCover.files[m.file]!==m.sha256||hash(read(new URL(m.source.pack+'/'+m.source.file,art)))!==m.source.sha256||hash(read(new URL(m.texture.pack+'/'+m.texture.file,art)))!==m.texture.sha256)throw Error('Stale foliage proxy: '+m.file);
const outskirtsCrown='4601ae8458c31c7316e0ccb442fcdb763518d394e47760c57119bdee470adc18';
if(hash(read(new URL('yavin-fringe/jacaranda-horizon.png',art)))!==outskirtsCrown || canopy.files['jacaranda.png']!=='7805b6a8d78db836e44b91f951fcae9f4de680ef125cacd6b158565bfd97a641')throw Error('Stale scenic canopy');
const recipe = {
  job: id, farCover,
  outskirts:{treatment:direction.outskirts.treatment,seed:1977,treeClass:direction.outskirts.foliage[0],crown:outskirtsCrown},
  direction: hash(JSON.stringify(direction)),
  canopy,
  edition: 'foc',
  path: job.identity.path.replaceAll('\\', '/'),
  ted: job.identity.ted,
  option: 'yavinLandscape',
  policy,
  stamp,
  slots,
  donors,
  zones,composition,
  grove: { kinds: ['fern'], files: Object.fromEntries(names.map(n => [n, hash(read(new URL(n, grove)))])) }
};
write(
  new URL('../../public/js/yavin-recipe.js', import.meta.url),
  '// Reviewed FoC Yavin 4 ground binding. Generated by tools/remaster/bind-yavin.mjs.\nexport const yavinRecipe = ' +
    JSON.stringify(recipe, null, 2) +
    ';\n'
);
